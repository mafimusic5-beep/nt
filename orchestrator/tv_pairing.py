"""Short-lived, end-to-end encrypted QR relay for activating an Android TV.

No activation code passes through the relay in plaintext. The phone encrypts it
to a fresh RSA-OAEP key generated by the TV; only that TV can decrypt it and
complete the existing signed /api/activate flow and device-limit checks.
"""
import base64
import hashlib
import hmac
import secrets
import sqlite3
import time

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from fastapi import APIRouter, Request
from fastapi.responses import HTMLResponse, JSONResponse
from pydantic import BaseModel, Field

from config import DATABASE_PATH


router = APIRouter(prefix="/api/tv/pair", tags=["tv-pairing"])
PAIR_TTL_SECONDS = 300
TICKET_BYTES = 24
POLL_SECRET_BYTES = 32


class StartPairRequest(BaseModel):
    public_key: str = Field(min_length=256, max_length=1024)


class SubmitPairRequest(BaseModel):
    ticket: str = Field(min_length=24, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")
    ciphertext: str = Field(min_length=300, max_length=1024, pattern=r"^[A-Za-z0-9+/=]+$")


class PollPairRequest(BaseModel):
    ticket: str = Field(min_length=24, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")
    poll_secret: str = Field(min_length=32, max_length=128, pattern=r"^[A-Za-z0-9_-]+$")


def _db():
    connection = sqlite3.connect(DATABASE_PATH, timeout=10.0)
    connection.row_factory = sqlite3.Row
    return connection


def ensure_tv_pair_storage():
    with _db() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS tv_pairing (
                ticket TEXT PRIMARY KEY,
                poll_secret_hash TEXT NOT NULL,
                public_key TEXT NOT NULL,
                ciphertext TEXT NOT NULL DEFAULT '',
                state TEXT NOT NULL DEFAULT 'waiting',
                expires_at INTEGER NOT NULL
            )
        """)
        db.execute("CREATE INDEX IF NOT EXISTS idx_tv_pair_expires ON tv_pairing(expires_at)")


def _error(reason, status):
    return JSONResponse(
        status_code=status,
        content={"ok": False, "reason": reason},
        headers={"Cache-Control": "no-store"},
    )


def _check_origin(request: Request):
    origin = request.headers.get("origin", "")
    return not origin or origin == "https://skryon.ru"


@router.post("/start")
def start_pairing(payload: StartPairRequest):
    try:
        key_bytes = base64.b64decode(payload.public_key, validate=True)
        key = serialization.load_der_public_key(key_bytes)
        if not isinstance(key, rsa.RSAPublicKey) or key.key_size != 2048:
            return _error("invalid_tv_public_key", 400)
    except (ValueError, TypeError):
        return _error("invalid_tv_public_key", 400)

    ticket = secrets.token_urlsafe(TICKET_BYTES)
    poll_secret = secrets.token_urlsafe(POLL_SECRET_BYTES)
    expiry = int(time.time()) + PAIR_TTL_SECONDS
    with _db() as db:
        db.execute("DELETE FROM tv_pairing WHERE expires_at < ?", (int(time.time()),))
        db.execute(
            "INSERT INTO tv_pairing(ticket, poll_secret_hash, public_key, expires_at) VALUES(?, ?, ?, ?)",
            (ticket, hashlib.sha256(poll_secret.encode("ascii")).hexdigest(), payload.public_key, expiry),
        )
    return {
        "ok": True,
        "ticket": ticket,
        "poll_secret": poll_secret,
        "url": "https://skryon.ru/api/tv/pair?ticket=" + ticket,
        "expires_in": PAIR_TTL_SECONDS,
    }


@router.get("/info")
def pair_info(ticket: str = ""):
    if len(ticket) != 32 or not all(c.isalnum() or c in "-_" for c in ticket):
        return _error("pair_not_found", 404)
    with _db() as db:
        row = db.execute(
            "SELECT public_key, state, expires_at FROM tv_pairing WHERE ticket = ?",
            (ticket,),
        ).fetchone()
    if row is None or row["expires_at"] <= int(time.time()) or row["state"] != "waiting":
        return _error("pair_expired_or_used", 410)
    return {"ok": True, "public_key": row["public_key"], "expires_in": row["expires_at"] - int(time.time())}


@router.post("/submit")
def pair_submit(payload: SubmitPairRequest, request: Request):
    if not _check_origin(request):
        return _error("invalid_origin", 403)
    try:
        ciphertext = base64.b64decode(payload.ciphertext, validate=True)
    except ValueError:
        return _error("invalid_ciphertext", 400)
    if len(ciphertext) != 256:
        return _error("invalid_ciphertext", 400)
    with _db() as db:
        db.execute("BEGIN IMMEDIATE")
        cur = db.execute(
            """
            UPDATE tv_pairing SET ciphertext = ?, state = 'submitted'
            WHERE ticket = ? AND state = 'waiting' AND expires_at > ?
            """,
            (payload.ciphertext, payload.ticket, int(time.time())),
        )
        if cur.rowcount != 1:
            return _error("pair_expired_or_used", 410)
    return {"ok": True, "status": "sent"}


@router.post("/poll")
def pair_poll(payload: PollPairRequest):
    secret_hash = hashlib.sha256(payload.poll_secret.encode("ascii")).hexdigest()
    with _db() as db:
        db.execute("BEGIN IMMEDIATE")
        row = db.execute(
            "SELECT poll_secret_hash, ciphertext, state, expires_at FROM tv_pairing WHERE ticket = ?",
            (payload.ticket,),
        ).fetchone()
        if row is None:
            return _error("pair_not_found", 404)
        if not hmac.compare_digest(row["poll_secret_hash"], secret_hash):
            return _error("pair_unauthorized", 401)
        if row["expires_at"] <= int(time.time()):
            db.execute("DELETE FROM tv_pairing WHERE ticket = ?", (payload.ticket,))
            return _error("pair_expired", 410)
        if row["state"] == "submitted":
            db.execute("DELETE FROM tv_pairing WHERE ticket = ?", (payload.ticket,))
            return {"ok": True, "status": "submitted", "ciphertext": row["ciphertext"]}
        return {"ok": True, "status": "waiting"}


